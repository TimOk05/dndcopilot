def entries_from_pairs(lines):
    entries = []
    for line in lines:
        roll, first, second = line
        entries.append({"roll": roll, "first": first, "second": second})
    return entries


def entries_from_names(lines):
    entries = []
    for roll, male, female, family in lines:
        entries.append({"roll": roll, "male": male, "female": female, "family": family})
    return entries


def weighted(lines):
    entries = []
    for roll_min, roll_max, value in lines:
        entries.append({"roll_min": roll_min, "roll_max": roll_max, "value": value})
    return entries


def menu(lines):
    entries = []
    for roll, dish, drink in lines:
        entries.append({"roll": roll, "dish": dish, "drink": drink})
    return entries


